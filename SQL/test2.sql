    YEAR(NGHD) AS Nam,
    MONTH(NGHD) AS Thang,
    SUM(TRIGIA) AS DoanhThuThang
FROM 
    HOADON
WHERE 
    YEAR(NGHD) = 2006
GROUP BY 
    YEAR(NGHD), MONTH(NGHD)
ORDER BY 
    Nam, Thang;
