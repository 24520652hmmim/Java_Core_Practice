SELECT TOP 1 T1.MAKH, T1.HOTEN, COUNT(T2.SOHD) AS SoLanMuaHang
FROM KHACHHANG T1
INNER JOIN HOADON T2 ON T1.MAKH = T2.MAKH
WHERE T1.MAKH IN (
    SELECT TOP 10 MAKH
    FROM KHACHHANG
    ORDER BY DOANHSO DESC
)
GROUP BY T1.MAKH, T1.HOTEN
ORDER BY SoLanMuaHang DESC;