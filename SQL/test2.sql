SELECT HD.SOHD
FROM HOADON HD
JOIN CTHD CT ON HD.SOHD = CT.SOHD
JOIN SANPHAM SP ON CT.MASP = SP.MASP
WHERE SP.NUOCSX = N'Viet Nam'
GROUP BY HD.SOHD
HAVING COUNT(DISTINCT CT.MASP) = 3;


