CREATE TRIGGER trg_ins_upd_KetQuaThi_LanThi
ON KETQUATHI
FOR INSERT, UPDATE
AS
BEGIN
    IF EXISTS (
        SELECT * FROM inserted i
        WHERE i.LANTHI > 1 
          AND EXISTS (
              SELECT 1 FROM KETQUATHI kq 
              WHERE kq.MAHV = i.MAHV 
                AND kq.MAMH = i.MAMH 
                AND kq.LANTHI = i.LANTHI - 1 
                AND kq.DIEM >= 5
          )
    )
    BEGIN
        PRINT 'Lỗi: Học viên đã đạt ở lần thi trước, không được thi lại.'
        ROLLBACK TRANSACTION
    END
END;
