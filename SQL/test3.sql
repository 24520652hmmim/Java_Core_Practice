CREATE TRIGGER trg_ins_kqt ON KETQUATHI
FOR INSERT, UPDATE
AS
BEGIN
	IF EXISTS (SELECT *
		FROM INSERTED I
		JOIN HOCVIEN HV ON HV.MAHV = I.MAHV
		WHERE NOT EXISTS (
			SELECT *
			FROM GIANGDAY GD
			WHERE GD.MALOP = HV.MALOP
