CREATE TRIGGER trg_ins_kh ON HOADON
FOR INSERT, UPDATE
AS
BEGIN
	IF EXISTS (SELECT *
		FROM KHACHHANG K
		JOIN (
			SELECT MAKH, SUM(TRIGIA) AS TONGTRIGIA
			FROM HOADON
			WHERE MAKH IS NOT NULL
			GROUP BY MAKH
		) HD ON K.MAKH = HD.MAKH
		JOIN INSERTED I ON I.MAKH = K.MAKH
		WHERE K.DOANHSO <> HD.TONGTRIGIA)
	BEGIN
		RAISERROR ('LOI: DOANH SO KHONG HOP LE!', 16, 1) ;
		ROLLBACK TRANSACTION
	END
	ELSE
	BEGIN
		PRINT 'THEM MOI HOA DON THANH CONG!'
	END
END
