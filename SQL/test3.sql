CREATE TRIGGER trg_ins_gd ON GIANGDAY
FOR INSERT, UPDATE
AS
BEGIN
	IF EXISTS (SELECT *
FROM (
            SELECT MALOP, HOCKY, NAM
            FROM INSERTED I
            GROUP BY MALOP, HOCKY, NAM
        ) IA
        WHERE (
            SELECT COUNT(*)
            FROM GIANGDAY GD
            WHERE GD.MALOP = IA.MALOP
              AND GD.HOCKY = IA.HOCKY
              AND GD.NAM   = IA.NAM
        ) > 3)
	BEGIN
		RAISERROR ('LOI: MOI HOC KY MOI LOP CHI HOC TOI DA 3 MON!', 16, 1) ;
		ROLLBACK TRANSACTION
	END
	ELSE
	BEGIN
		PRINT 'THEM MOI THANH CONG!'
	END
END

