CREATE TRIGGER trg_ins_tg ON HOADON
FOR INSERT, UPDATE
AS
BEGIN
	IF EXISTS (SELECT *
		FROM INSERTED I
		JOIN (
			SELECT C.SOHD, SUM(C.SL * SP.GIA) AS THANHTIEN
			FROM CTHD C
			JOIN SANPHAM SP ON C.MASP = SP.MASP
			GROUP BY C.SOHD
		) TG ON TG.SOHD = I.SOHD
		WHERE I.TRIGIA <> TG.THANHTIEN)
	BEGIN
		RAISERROR ('LOI: TRI GIA KHONG HOP IE!', 16, 1) ;
		ROLLBACK TRANSACTION
	END
	ELSE
	BEGIN
		PRINT 'THEM MOI HOA DON THANH CONG!'
	END
END

