CREATE TRIGGER trg_ins_hvien ON HOCVIEN
FOR INSERT, UPDATE, DELETE
AS
BEGIN
	IF EXISTS (SELECT *
		FROM (
            SELECT MALOP FROM INSERTED
			UNION
            SELECT MALOP FROM DELETED
        ) IA
        WHERE (
            SELECT COUNT(*)
            FROM HOCVIEN HV
            WHERE HV.MALOP = IA.MALOP
		) <> (
			SELECT SISO
			FROM LOP L
			WHERE L.MALOP = IA.MALOP
		)
	)
	BEGIN
		RAISERROR ('LOI: SI SO LOP KHONG DUNG VOI SO LUONG HOC VIEN!', 16, 1) ;
		ROLLBACK TRANSACTION
	END
	ELSE
	BEGIN
		PRINT 'THEM MOI THANH CONG!'
	END
END

