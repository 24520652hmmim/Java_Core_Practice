CREATE TRIGGER trg_ins_hd ON HOADON
FOR INSERT
AS
BEGIN
	IF EXISTS (SELECT *
		FROM INSERTED, KHACHHANG
		WHERE INSERTED.MAKH = KHACHHANG.MAKH
		AND NGHD < NGDK)
	BEGIN
		RAISERROR ('LOI: NGAY HOA DON KHONG HOP IE!', 16, 1) ;
		ROLLBACK TRANSACTION
	END
	ELSE
	BEGIN
		PRINT 'THEM MOI HOA DON THANH CONG!'
	END
END

