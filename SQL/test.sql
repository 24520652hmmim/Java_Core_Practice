SELECT GV.MAGV, GV.HOTEN, GD.NAM, GD.HOCKY
FROM GIAOVIEN GV
JOIN GIANGDAY GD ON GV.MAGV = GD.MAGV
GROUP BY GV.MAGV, GV.HOTEN, GD.NAM, GD.HOCKY
HAVING COUNT(*) >= ALL (
    SELECT COUNT(*)
    FROM GIANGDAY G
    WHERE G.NAM = GD.NAM
      AND G.HOCKY = GD.HOCKY
    GROUP BY G.MAGV
)
ORDER BY GD.NAM, GD.HOCKY;

