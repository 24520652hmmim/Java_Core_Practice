SELECT HV.MAHV, HV.HO + ' ' + HV.TEN AS HoTen, HV.MALOP
FROM HOCVIEN HV
JOIN KETQUATHI KQ ON HV.MAHV = KQ.MAHV
WHERE KQ.DIEM BETWEEN 9 AND 10
GROUP BY HV.MAHV, HV.HO, HV.TEN, HV.MALOP
HAVING COUNT(*) >= ALL (
    SELECT COUNT(*)
    FROM HOCVIEN H
    JOIN KETQUATHI K ON H.MAHV = K.MAHV
    WHERE K.DIEM BETWEEN 9 AND 10
      AND H.MALOP = HV.MALOP
    GROUP BY H.MAHV
);


